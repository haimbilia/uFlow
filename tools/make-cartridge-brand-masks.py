"""Bake small moulded platform wordmarks for the built-in cartridge materials."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1];w,h=256,48
lines=['// Generated by tools/make-cartridge-brand-masks.py.','#pragma once','#include <cstdint>','namespace CartridgeModels {','inline constexpr unsigned BrandWidth=256,BrandHeight=48;','inline constexpr uint8_t BrandPixels[4][3072]={']
for title in ['NINTENDO 64','GAME BOY ADVANCE','Nintendo GAME BOY','Nintendo DS']:
 im=Image.new('L',(w*2,h*2));d=ImageDraw.Draw(im)
 for size in range(78,10,-1):
  f=ImageFont.truetype(str(root/'app/data/glass.ttf'),size);box=d.textbbox((0,0),title,font=f)
  if box[2]-box[0]<w*2-12:break
 d.text(((w*2-(box[2]-box[0]))/2-box[0],(h*2-(box[3]-box[1]))/2-box[1]),title,font=f,fill=255)
 pixels=list(im.resize((w,h),Image.Resampling.LANCZOS).get_flattened_data());data=[]
 for i in range(0,len(pixels),4):data.append(sum(round(pixels[i+k]/85)<<(6-2*k) for k in range(4)))
 lines.append('{'+','.join(map(str,data))+'},')
lines+=['};','}'];(root/'app/source/cartridge_brand_masks.hpp').write_text('\n'.join(lines)+'\n')
