"""Generate hash-only iNES recovery metadata; never reads or modifies ROMs."""
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
source = root / 'tooling/nes-db/nes20db.xml'
expected = 'a60757b92f2f3df9447aa50e004aabe9f4cb0845bb037afca118ff89b5913ae3'
assert hashlib.sha256(source.read_bytes()).hexdigest() == expected, 'Database revision changed'
entries = {}
ambiguous = set()
for game in ET.parse(source).getroot():
    def value(tag, key='size', default=0):
        node = game.find(tag)
        return int(node.get(key, default)) if node is not None else default
    rom, pcb = game.find('rom'), game.find('pcb')
    if rom is None or pcb is None:
        continue
    prg, chr = value('prgrom'), value('chrrom')
    mapper, sub = value('pcb', 'mapper'), value('pcb', 'submapper')
    # Only metadata faithfully expressible for the legacy VC interface.
    # MMC1 SEROM/SHROM (sub5) has fixed32K PRG, also represented by iNES MMC1.
    if not (0 < prg <= 255*16384 and prg % 16384 == 0 and chr <= 255*8192 and chr % 8192 == 0):
        continue
    if mapper >= 256 or (sub != 0 and not (mapper == 1 and sub == 5 and prg == 32768)):
        continue
    if value('console', 'type') != 0 or value('console', 'region') > 2:
        continue
    if value('prgram') + value('prgnvram') > 8192 or value('chrram') not in (0, 8192) or value('chrnvram'):
        continue
    if value('trainer') or value('miscrom') or pcb.get('mirroring') not in ('H', 'V', '4'):
        continue
    if value('rom') != prg + chr:
        continue
    header = bytearray(b'NES\x1a' + bytes(12))
    header[4:6] = bytes([prg//16384, chr//8192])
    header[6] = (mapper & 15)*16 | {'H':0, 'V':1, '4':8}[pcb.get('mirroring')] | (2 if value('pcb', 'battery') else 0)
    header[7] = mapper & 240
    header[8] = 1 if value('prgram') + value('prgnvram') else 0
    header[9] = 1 if value('console', 'region') == 1 else 0
    sha = rom.get('sha1').lower()
    if sha in entries and entries[sha] != header:
        ambiguous.add(sha)
    entries[sha] = header
for sha in ambiguous:
    del entries[sha]
out = ['#pragma once', '// Generated by tools/generate-nes-db.py; hash/board metadata, no ROM data.',
       '// NES20DB (NewRisingSun), 2021-12-25; see docs/nes-formats.md for provenance.',
       'namespace NesRom {', 'struct DbEntry { unsigned char sha[20], header[16]; };',
       'inline constexpr DbEntry database[] = {']
for sha, header in sorted(entries.items()):
    def cbytes(data): return '{' + ','.join('0x%02x' % b for b in data) + '}'
    out.append('{' + cbytes(bytes.fromhex(sha)) + ',' + cbytes(header) + '},')
out += ['};', '}']
(root/'app/source/nes_database.hpp').write_text('\n'.join(out)+'\n', encoding='utf-8')
print(f'Generated {len(entries)} exact-SHA1 headers; excluded {len(ambiguous)} ambiguous hashes')
