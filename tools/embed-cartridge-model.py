"""Embed NES geometry with a static BSP for correct painter ordering of recesses.
Only build-time polygon splitting allocates; runtime traverses the compiled tree.
"""
from pathlib import Path
import argparse, math
EPS=1e-5
def sub(a,b): return tuple(x-y for x,y in zip(a,b))
def dot(a,b): return sum(x*y for x,y in zip(a,b))
def cross(a,b): return (a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])
def plane(p):
 n=cross(sub(p[1],p[0]),sub(p[2],p[0])); length=math.sqrt(dot(n,n))
 return tuple(x/length for x in n),length*.5

def build(polys,nodes,ordered,depth=0):
 if not polys:return -1
 # Large planes first keep the shell tree shallow. Split crossing polygons so
 # average triangle depth cannot expose recessed sidewalls through the shell.
 def score(candidate):
  cn,_=plane(candidate);cd=dot(cn,candidate[0]);f=b=split=0
  for poly in polys:
   ds=[dot(cn,v)-cd for v in poly];pos=max(ds)>EPS;neg=min(ds)<-EPS
   split+=pos and neg;f+=pos;b+=neg
  return split*12+abs(f-b)
 candidates=sorted(polys,key=lambda p:plane(p)[1],reverse=True)[:48]
 splitter=min(candidates,key=score);n,_=plane(splitter);d=dot(n,splitter[0])
 front=[];back=[];flat=[]
 for p in polys:
  ds=[dot(n,v)-d for v in p]
  pos=any(x>EPS for x in ds);neg=any(x<-EPS for x in ds)
  if not pos and not neg:flat.append(p);continue
  if not neg:front.append(p);continue
  if not pos:back.append(p);continue
  fp=[];bp=[]
  for i,a in enumerate(p):
   b=p[(i+1)%len(p)];da=ds[i];db=ds[(i+1)%len(p)]
   if da>=-EPS:fp.append(a)
   if da<=EPS:bp.append(a)
   if (da>EPS and db<-EPS) or (da<-EPS and db>EPS):
    t=da/(da-db);v=tuple(x+t*(y-x) for x,y in zip(a,b));fp.append(v);bp.append(v)
  for fragment,target in [(fp,front),(bp,back)]:
   for i in range(1,len(fragment)-1):
    tri=[fragment[0],fragment[i],fragment[i+1]]
    if dot(cross(sub(tri[1],tri[0]),sub(tri[2],tri[0])),cross(sub(tri[1],tri[0]),sub(tri[2],tri[0])))>1e-20:target.append(tri)
 index=len(nodes);start=len(ordered);ordered.extend(flat);nodes.append(None)
 fi=build(front,nodes,ordered,depth+1);bi=build(back,nodes,ordered,depth+1)
 nodes[index]=(n,d,fi,bi,start,len(flat))
 return index

p=argparse.ArgumentParser();p.add_argument("directory",type=Path);p.add_argument("output",type=Path)
p.add_argument("--system",choices=["nes","snes","n64","gba","gb","ds","hucard","genesis"],default="nes");args=p.parse_args()
system=args.system;namespace={"nes":"NesCartridge","snes":"SnesCartridge","n64":"N64Cartridge","gba":"GbaCartridge","gb":"GbCartridge","ds":"DsCartridge","hucard":"HuCardCartridge","genesis":"GenesisCartridge"}[system]
if system!="nes":EPS=1e-7
lines=[f"// Generated by tools/embed-cartridge-model.py. Source: user-supplied {system.upper()} model.","#pragma once","#include <cstdint>",f"namespace {namespace} {{", "struct Point {float x,y,z;};", "struct Triangle {uint16_t a,b,c;};", "struct BspNode {Point normal;float distance;int front,back;unsigned start,count;};"]
if system not in ("nes","snes"):
 lines=lines[:3]+['#include "cartridge_geometry.hpp"',f"namespace {namespace} {{","using CartridgeGeometry::Point;","using CartridgeGeometry::Triangle;","using CartridgeGeometry::BspNode;"]
nearFaceCount=0
for name,filename in [("Near",system+"-cart.obj"),("Far",system+"-cart-small.obj")]:
 vertices=[];faces=[]
 for line in (args.directory/filename).read_text().splitlines():
  f=line.split()
  if f and f[0]=="v":vertices.append(tuple(float(x) for x in f[1:4]))
  if f and f[0]=="f":faces.append([int(x.split("/")[0])-1 for x in f[1:4]])
 polys=[[vertices[i] for i in f] for f in faces];nodes=[];ordered=[];build(polys,nodes,ordered)
 vertices=[];faces=[];lookup={}
 for p in ordered:
  face=[]
  for v in p:
   key=tuple(round(x,9) for x in v)
   if key not in lookup:lookup[key]=len(vertices);vertices.append(key)
   face.append(lookup[key])
  faces.append(face)
 # Stitch BSP split points into adjacent triangle edges. SDL's rasterizer
 # otherwise leaves moving subpixel cracks at T-junctions.
 originalVertices=list(vertices);stitched=[];offsets=[0]
 for face in faces:
  boundary=[]
  for j,a in enumerate(face):
   b=face[(j+1)%3];va=vertices[a];vb=vertices[b];edge=sub(vb,va);length2=dot(edge,edge)
   inserts=[]
   for k,v in enumerate(originalVertices):
    if k in (a,b) or length2<1e-20:continue
    t=dot(sub(v,va),edge)/length2
    if not 1e-6<t<1-1e-6:continue
    error=sub(sub(v,va),tuple(t*x for x in edge))
    if dot(error,error)<(1e-14 if system!="nes" else 1e-12):inserts.append((t,k))
   boundary.append(a);boundary.extend(k for t,k in sorted(inserts))
  if len(boundary)==3:stitched.append(face)
  else:
   center=tuple(sum(vertices[k][axis] for k in face)/3 for axis in range(3))
   ci=len(vertices);vertices.append(center)
   stitched.extend([ci,boundary[j],boundary[(j+1)%len(boundary)]] for j in range(len(boundary)))
  offsets.append(len(stitched))
 nodes=[(n,d,fi,bi,offsets[start],offsets[start+count]-offsets[start]) for n,d,fi,bi,start,count in nodes]
 faces=stitched
 assert len(vertices)<65536
 print(name,len(vertices),'vertices',len(faces),'triangles',len(nodes),'BSP nodes')
 if name=="Near":nearFaceCount=len(faces)
 elif len(faces)>nearFaceCount:
  # A nominally simpler mesh can need more splits. Reuse the smaller BSP.
  lines.extend(["inline constexpr auto &FarVertices=NearVertices;", "inline constexpr auto &FarFaces=NearFaces;", "inline constexpr auto &FarNodes=NearNodes;"])
  continue
 lines.append("inline constexpr Point "+name+"Vertices[]={")
 lines.extend("{"+",".join(f"{x:.9f}f" for x in v)+"}," for v in vertices);lines.append("};")
 lines.append("inline constexpr Triangle "+name+"Faces[]={")
 lines.extend("{"+",".join(map(str,f))+"}," for f in faces);lines.append("};")
 lines.append("inline constexpr BspNode "+name+"Nodes[]={")
 lines.extend("{{"+",".join(f"{x:.9f}f" for x in n)+"},"+f"{d:.9f}f,{fi},{bi},{start},{count}"+"}," for n,d,fi,bi,start,count in nodes);lines.append("};")
lines.append("}");args.output.write_text("\n".join(lines)+"\n")
