"""Bake the Genesis rear mould lettering as a compact two-bit relief mask."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
root=Path(__file__).resolve().parents[1]
width,height=512,256
mask=Image.new("L",(width*2,height*2))
draw=ImageDraw.Draw(mask)
font=root/"app/data/glass.ttf"
def text(x,y,value,size):
    draw.text((x*2,y*2),value,font=ImageFont.truetype(str(font),size*2),fill=255)
text(182,4,"SEGA",46)
text(180,56,"MADE IN JAPAN",12)
text(205,105,"CAUTION",20)
for y,line in enumerate(("Avoid exposing cartridge to extreme temperatures.",
                         "Be careful not to immerse cartridge in water.",
                         "For protection place cartridge inside",
                         "protective plastic case when not in use.")):
    text(32,139+y*22,line,13)
mask=mask.resize((width,height),Image.Resampling.LANCZOS)
pixels=list(mask.get_flattened_data())
packed=[sum(round(pixels[i+k]/85)<<(6-2*k) for k in range(4)) for i in range(0,len(pixels),4)]
out=["// Generated by tools/make-genesis-relief.py.","#pragma once","#include <cstdint>",
     "namespace GenesisCartridge {",f"inline constexpr unsigned ReliefWidth={width},ReliefHeight={height};",
     "inline constexpr uint8_t ReliefPixels[]={"]
out.extend(",".join(map(str,packed[i:i+96]))+"," for i in range(0,len(packed),96))
out.extend(["};","}"])
(root/"app/source/genesis_relief.hpp").write_text("\n".join(out)+"\n")
