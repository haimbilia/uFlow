"""Generate the shared rear caution label as an embedded monochrome mask.

Typography is drawn cleanly; this does not crop or alter a reference photograph.

"""

from pathlib import Path

from PIL import Image,ImageDraw,ImageFont

W,H=768,312

im=Image.new("L",(W,H));d=ImageDraw.Draw(im)

font=Path("C:/Windows/Fonts/arialbd.ttf")

def text(x,y,s,size):d.text((x,y),s,font=ImageFont.truetype(str(font),size),fill=255)

d.rounded_rectangle((2,2,W-3,H-3),radius=17,outline=170,width=2)

text(250,16,"CAUTION",44);text(630,29,"REV-A",18)

d.line((242,70,473,70),fill=255,width=3)

text(26,90,"• DO NOT STORE IN EXTREME TEMPERATURES.",25)

text(26,135,"• DO NOT IMMERSE IN WATER.",25)

text(26,180,"• DO NOT CLEAN WITH BENZENE, THINNER,",25)

text(45,212,"ALCOHOL OR OTHER SUCH SOLVENTS.",25)

text(292,259,"Nintendo",32)

im=im.resize((512,208),Image.Resampling.LANCZOS)

im.save("assets/models/nes/back-label.png")

# Two bits per pixel preserve softened lettering with a small embedded payload.

v=[round(x/85) for x in im.getdata()];packed=[]

for i in range(0,len(v),4):packed.append(sum(v[i+j]<<(6-2*j) for j in range(4)))

lines=["// Generated by tools/make-nes-back-label.py.","#pragma once","namespace NesCartridge {", "inline constexpr unsigned BackLabelWidth=512,BackLabelHeight=208;", "inline constexpr unsigned char BackLabelPixels[]={"]

lines.extend(",".join(str(x) for x in packed[i:i+32])+"," for i in range(0,len(packed),32));lines.extend(["};","}"])

Path("app/source/nes_back_label.hpp").write_text("\n".join(lines)+"\n")
